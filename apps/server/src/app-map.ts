import { GameStateSchema } from "@vtt/domain";
import { API_VERSION, GAME_COMMANDS, REALTIME_PROTOCOL_VERSION } from "@vtt/api-contract";
import { openApiDocument } from "./api-routes.js";

/**
 * Renders the generated app map (`docs/app-map.md`). Pure: reads the `GameState` schema, the api-contract
 * command/scope map and the OpenAPI document and returns deterministic markdown. A freshness test fails
 * when those change without `npm run map`. Reports only what it can derive, so it cannot go stale unnoticed.
 */

const HTTP_METHODS = new Set(["get", "post", "put", "patch", "delete", "options", "head", "trace"]);

/** Command types grouped by their namespace (the segment before the first dot) for scannability. */
function namespaceOf(commandType: string): string {
  const dot = commandType.indexOf(".");
  return dot === -1 ? commandType : commandType.slice(0, dot);
}

export function renderAppMap(): string {
  const stateFields = Object.keys(GameStateSchema.shape).sort();
  const commands = Object.entries(GAME_COMMANDS)
    .map(([type, route]) => ({ type, scope: String(route.scope) }))
    .sort((a, b) => a.type.localeCompare(b.type));
  const namespaces = [...new Set(commands.map((command) => namespaceOf(command.type)))].sort();
  const httpPaths = Object.entries(openApiDocument.paths)
    .map(([path, item]) => ({
      path,
      methods: Object.keys(item as Record<string, unknown>)
        .filter((key) => HTTP_METHODS.has(key))
        .map((method) => method.toUpperCase())
        .sort()
    }))
    .sort((a, b) => a.path.localeCompare(b.path));

  const lines: string[] = [];
  lines.push("# App map (generated by `npm run map`, do not edit by hand)");
  lines.push("");
  lines.push("The state shape, every command with its integration scope, and every HTTP path, read from the code. A");
  lines.push("test (`apps/server/test/app-map.test.ts`) fails when this is stale. Search it for a name rather than");
  lines.push("reading it whole. `docs/ARCHITECTURE.md` explains how the pieces fit together.");
  lines.push("");
  lines.push(`- API version \`${API_VERSION}\` · realtime protocol \`${REALTIME_PROTOCOL_VERSION}\``);
  lines.push(`- ${stateFields.length} GameState fields · ${commands.length} commands · ${httpPaths.length} HTTP paths`);
  lines.push("");

  lines.push("## GameState shape");
  lines.push("");
  lines.push("Top-level fields of the authoritative `GameState` (`packages/domain` `GameStateSchema`), the");
  lines.push("single JSON blob the server persists and projects per role.");
  lines.push("");
  for (const field of stateFields) lines.push(`- \`${field}\``);
  lines.push("");

  lines.push("## Commands");
  lines.push("");
  lines.push("The mutation surface shared by both transports (Socket.IO + HTTP `/api/v1`); each requires the");
  lines.push("listed integration scope. Adding one: its typed socket event in domain `ClientToServerEvents`, its");
  lines.push(
    "schema in `packages/domain/src/commands.ts`, its route and scope in `GAME_COMMANDS` (`packages/api-contract`), and"
  );
  lines.push("one table entry under `apps/server/src/commands/`. Both transports register from that table, and");
  lines.push("the OpenAPI document generates the command's operation from it. Then the projection decision.");
  lines.push("");
  lines.push(`Namespaces: ${namespaces.map((namespace) => `\`${namespace}\``).join(", ")}.`);
  lines.push("");
  lines.push("| Command | Scope |");
  lines.push("| --- | --- |");
  for (const command of commands) lines.push(`| \`${command.type}\` | \`${command.scope}\` |`);
  lines.push("");

  lines.push("## HTTP surface");
  lines.push("");
  lines.push("Every path in the served OpenAPI document (`GET /api/v1/openapi.json`), which is generated");
  lines.push("from the route registry in `packages/api-contract/src/routes/`.");
  lines.push("");
  for (const entry of httpPaths) lines.push(`- \`${entry.methods.join(" ")} ${entry.path}\``);
  lines.push("");

  return lines.join("\n");
}
